"""Synthetic curve tables laid out like a terminal curve screen (shared by the unit and
live suites). The numbers are test fixtures generated by a smooth formula: they are not
market data and are never shipped by the server."""

from __future__ import annotations

import math

#: the 32 labels of a 1W..50Y screen, as the screen writes them and in compact form
SCREEN_LABELS: list[tuple[str, str, float]] = (
    [(f"{n} WK", f"{n}W", n * 7 / 365.25) for n in (1, 2, 3)]
    + [(f"{n} MO", f"{n}M", n / 12) for n in (*range(1, 13), 18)]
    + [
        (f"{n} YR", f"{n}Y", float(n))
        for n in (2, 3, 4, 5, 6, 7, 8, 9, 10, 12, 15, 20, 25, 30, 40, 50)
    ]
)
assert len(SCREEN_LABELS) == 32

HEADER6 = ["Term", "Market Rate", "Shift", "Shifted Rate", "Zero Rate", "Discount"]


def _cols(t: float) -> tuple[str, str, str, str, str]:
    par = 4.30 - 0.9 * (1 - math.exp(-t / 4))  # percent
    zero = par + 0.02 * (1 - math.exp(-t / 10))
    df = math.exp(-zero / 100 * t)
    return f"{par:.5f}", "0.000", f"{par:.5f}", f"{zero:.5f}", f"{df:.6f}"


def two_column(screen_labels: bool) -> str:
    """``label<TAB>par%`` rows, labels as on the screen (``1 WK``) or compact (``1W``)."""
    return "\n".join(
        f"{lab if screen_labels else short}\t{_cols(t)[0]}%" for lab, short, t in SCREEN_LABELS
    )


def six_column(sep: str = "\t") -> str:
    """The six-column screen tab (Term, Market Rate, Shift, Shifted Rate, Zero Rate,
    Discount) with ``sep`` between cells; rates in percent without a ``%`` sign."""
    lines = [sep.join(HEADER6)]
    lines += [sep.join((lab, *_cols(t))) for lab, _, t in SCREEN_LABELS]
    return "\n".join(lines)


def expected_column(kind: str) -> list[float]:
    """The values the parser must read for ``kind`` from :func:`six_column` (as written,
    no percent flag: the screen prints percent figures without a ``%``)."""
    i = {"par": 0, "zero": 3, "discount": 4}[kind]
    return [float(_cols(t)[i]) for _, _, t in SCREEN_LABELS]
